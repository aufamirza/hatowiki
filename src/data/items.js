/** Semua benda: `items` ditambah tanaman dan collectible (diturunkan dari datanya sendiri). */
export const ALL_ITEMS = [
  ...items,
  ...Object.entries(OWN_DATA).flatMap(([segment, { type, entries }]) =>
    entries.map((entry) => ({
      id: `${segment}/${entry.slug}`,
      name: entry.name,
      type,
      image: entry.image,
      imageSize: entry.imageSize,
      source: entry.source,
    })),
  ),
]

const ITEMS_BY_ID = new Map(ALL_ITEMS.map((item) => [item.id, item]))

export function getItem(id) {
  return ITEMS_BY_ID.get(id)
}

const isText = (value) => typeof value === 'string' && value.trim() !== ''

/**
 * Memeriksa daftar benda terhadap skemanya. Dipakai saat development dan oleh scripts/heartodex-sync.mjs.
 * @param {Item[]} list
 * @returns {{ id: string, problems: string[] }[]} hanya benda yang bermasalah
 */
export function findItemProblems(list) {
  const seen = new Set()
  const report = []
  for (const item of list) {
    const problems = []
    const [segment, slug] = (item.id ?? '').split('/')
    if (!/^[a-z-]+\/[a-z0-9]+(-[a-z0-9]+)*$/.test(item.id ?? '')) problems.push('id harus berbentuk <bagian>/<slug>')
    if (seen.has(item.id)) problems.push('id dipakai lebih dari sekali')
    seen.add(item.id)
    if (!isText(item.name)) problems.push('name wajib diisi')
    const type = ITEM_TYPES[item.type]
    if (!type) problems.push(`type "${item.type}" tidak dikenal`)
    const generic = segment === 'any'
    if (OWN_DATA[segment]) problems.push(`benda ${segment}/* tidak disimpan di items.js; sumbernya src/data/${segment}/${segment}.js`)
    if (type && !generic && type.segment !== segment) problems.push(`awalan id "${segment}" tidak cocok dengan type ${item.type}`)
    if (!(item.image === null || isText(item.image))) problems.push('image harus teks atau null')
    const imagePaths = [`/images/items/${segment}-${slug}.webp`, ENTRY_IMAGE_DIRS[segment] && `${ENTRY_IMAGE_DIRS[segment]}/${slug}.webp`]
    if (item.image && !imagePaths.includes(item.image)) problems.push('image harus /images/items/<bagian>-<slug>.webp atau gambar entrinya sendiri')
    if (item.imageSize != null && !(item.imageSize.length === 2 && item.imageSize.every((v) => Number.isInteger(v) && v > 0))) {
      problems.push('imageSize harus [lebar, tinggi] bilangan bulat > 0')
    }
    if (item.image && item.imageSize == null) problems.push('imageSize wajib ada kalau image ada')
    if (generic ? item.source !== null : !isText(item.source)) problems.push(generic ? 'bahan generik tidak punya source' : 'source wajib diisi')
    if (problems.length) report.push({ id: item.id, problems })
  }
  return report
}

// Pemeriksaan data saat development supaya typo ketahuan begitu benda baru ditambahkan.
if (import.meta.env.DEV) {
  for (const { id, problems } of findItemProblems(items)) {
    console.warn(`[data benda] ${id}: ${problems.join('; ')}`)
  }
}
